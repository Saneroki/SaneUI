-- Basics: a window of plain widgets (texts, buttons, a check box, a slider, a bar, an edit box, a tooltip)
-- A scene is lab-only: it loads the addon files it shows (Lab.Addon, Lab.TOC) and may build things itself after
-- the login (Lab.OnLogin). Everything else in it is the game's API, as in the game.
Lab.OnLogin(function()
    local f = CreateFrame("Frame", "LabBasics", UIParent, "BackdropTemplate")
    f:SetSize(420, 330)
    f:SetPoint("CENTER")
    f:SetBackdrop({ bgFile = "Interface\\DialogFrame\\UI-DialogBox-Background-Dark",
        edgeFile = "Interface\\DialogFrame\\UI-DialogBox-Border", tile = true, tileSize = 32, edgeSize = 32,
        insets = { left = 11, right = 12, top = 12, bottom = 11 } })
    f:EnableMouse(true)
    f:SetMovable(true)
    f:RegisterForDrag("LeftButton")
    f:SetScript("OnDragStart", f.StartMoving)
    f:SetScript("OnDragStop", f.StopMovingOrSizing)
    tinsert(UISpecialFrames, "LabBasics")

    local title = f:CreateFontString(nil, "OVERLAY", "GameFontNormalLarge")
    title:SetPoint("TOP", 0, -20)
    title:SetText("Hello from the lab")

    local name = UnitName("player")
    local text = f:CreateFontString(nil, "OVERLAY", "GameFontHighlight")
    text:SetPoint("TOPLEFT", 24, -52)
    text:SetPoint("RIGHT", -24, 0)
    text:SetJustifyH("LEFT")
    text:SetText(("%s, level %d %s, in %s. |cff40ff40%s|r says: %s"):format(name, UnitLevel("player"),
        UnitClass("player"), GetZoneText(), GetGuildInfo("player") or "no guild", GetGuildRosterMOTD()))

    local button = CreateFrame("Button", nil, f)
    button:SetSize(140, 26)
    button:SetPoint("BOTTOMLEFT", 24, 24)
    button:SetNormalTexture("Interface\\Buttons\\UI-Panel-Button-Up")
    button:SetPushedTexture("Interface\\Buttons\\UI-Panel-Button-Down")
    button:SetHighlightTexture("Interface\\Buttons\\UI-Panel-Button-Highlight")
    for _, t in ipairs({ button:GetNormalTexture(), button:GetPushedTexture(), button:GetHighlightTexture() }) do
        t:SetTexCoord(0, 0.625, 0, 0.6875)
    end
    button:SetNormalFontObject("GameFontNormal")
    button:SetHighlightFontObject("GameFontHighlight")
    button:SetText("Say hello")
    button:SetScript("OnClick", function() SendChatMessage("Hello from the lab!", "GUILD") end)
    button:SetScript("OnEnter", function(self)
        GameTooltip:SetOwner(self, "ANCHOR_RIGHT")
        GameTooltip:SetText("Say hello")
        GameTooltip:AddLine("Sends a line to the guild: the fake server answers it.", 1, 1, 1, true)
        GameTooltip:Show()
    end)
    button:SetScript("OnLeave", GameTooltip_Hide)

    local check = CreateFrame("CheckButton", nil, f)
    check:SetSize(26, 26)
    check:SetPoint("TOPLEFT", 20, -120)
    check:SetNormalTexture("Interface\\Buttons\\UI-CheckBox-Up")
    check:SetPushedTexture("Interface\\Buttons\\UI-CheckBox-Down")
    check:SetHighlightTexture("Interface\\Buttons\\UI-CheckBox-Highlight", "ADD")
    check:SetCheckedTexture("Interface\\Buttons\\UI-CheckBox-Check")
    local label = check:CreateFontString(nil, "OVERLAY", "GameFontHighlight")
    label:SetPoint("LEFT", check, "RIGHT", 4, 0)
    label:SetText("A check box")

    local bar = CreateFrame("StatusBar", nil, f)
    bar:SetSize(220, 16)
    bar:SetPoint("TOPLEFT", 26, -160)
    bar:SetStatusBarTexture("Interface\\TargetingFrame\\UI-StatusBar")
    bar:SetStatusBarColor(0.1, 0.9, 0.2)
    bar:SetMinMaxValues(0, UnitHealthMax("player"))
    bar:SetValue(UnitHealth("player") * 0.7)
    local bg = bar:CreateTexture(nil, "BACKGROUND")
    bg:SetAllPoints()
    bg:SetColorTexture(0, 0, 0, 0.5)

    local slider = CreateFrame("Slider", nil, f)
    slider:SetSize(220, 17)
    slider:SetPoint("TOPLEFT", 26, -196)
    slider:SetOrientation("HORIZONTAL")
    slider:SetThumbTexture("Interface\\Buttons\\UI-SliderBar-Button-Horizontal")
    slider:GetThumbTexture():SetSize(32, 32)
    local track = slider:CreateTexture(nil, "BACKGROUND")
    track:SetPoint("LEFT")
    track:SetPoint("RIGHT")
    track:SetHeight(6)
    track:SetColorTexture(0.2, 0.2, 0.2, 1)
    slider:SetMinMaxValues(0, 100)
    slider:SetValueStep(1)
    slider:SetObeyStepOnDrag(true)
    slider:SetValue(40)
    slider:SetScript("OnValueChanged", function(self, value) bar:SetValue(UnitHealthMax("player") * value / 100) end)

    local edit = CreateFrame("EditBox", nil, f, "BackdropTemplate")
    edit:SetSize(220, 26)
    edit:SetPoint("TOPLEFT", 24, -236)
    edit:SetAutoFocus(false)
    edit:SetFontObject("ChatFontNormal")
    edit:SetTextInsets(6, 6, 0, 0)
    edit:SetBackdrop({ bgFile = "Interface\\Buttons\\WHITE8X8", edgeFile = "Interface\\Buttons\\WHITE8X8", edgeSize = 1 })
    edit:SetBackdropColor(0, 0, 0, 0.6)
    edit:SetBackdropBorderColor(0.5, 0.5, 0.5, 1)
    edit:SetScript("OnEnterPressed", function(self)
        SendChatMessage(self:GetText(), "SAY")
        self:SetText("")
        self:ClearFocus()
    end)

    local icon = f:CreateTexture(nil, "ARTWORK")
    icon:SetSize(48, 48)
    icon:SetPoint("TOPRIGHT", -28, -112)
    icon:SetTexture(GetInventoryItemTexture("player", 16))
    local hit = CreateFrame("Frame", nil, f)
    hit:SetAllPoints(icon)
    hit:EnableMouse(true)
    hit:SetScript("OnEnter", function(self)
        GameTooltip:SetOwner(self, "ANCHOR_RIGHT")
        GameTooltip:SetInventoryItem("player", 16)
    end)
    hit:SetScript("OnLeave", GameTooltip_Hide)

    local said = f:CreateFontString(nil, "OVERLAY", "GameFontNormalSmall")
    said:SetPoint("BOTTOMRIGHT", -24, 30)
    said:SetJustifyH("RIGHT")
    said:SetWidth(200)
    f:RegisterEvent("CHAT_MSG_GUILD")
    f:RegisterEvent("CHAT_MSG_SAY")
    f:SetScript("OnEvent", function(self, event, msg, sender)
        said:SetText(sender .. ": " .. msg)
    end)
end)
